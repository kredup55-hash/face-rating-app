from flask import Flask, render_template, request, jsonify
from openai import OpenAI
import base64
import os

app = Flask(__name__)

client = OpenAI(
    api_key=os.environ.get("OPENROUTER_API_KEY"),
    base_url="https://openrouter.ai/api/v1"
)

@app.route('/')
def index():
    return render_template('index.html')

@app.route('/analyze', methods=['POST'])
def analyze():
    try:
        file = request.files['photo']
        image_data = base64.b64encode(file.read()).decode('utf-8')

        prompt = """Ты — лучший в мире эксперт по эстетике лица и стилю.
Твоя методология объединяет: QOVES Studio (2000+ научных исследований),
PSL-метрики, систему типажей David Kibbe, Seasonal Color Analysis (12 сезонов),
подход David Zyla, практики ведущих российских имидж-консультантов.

ГЛАВНЫЙ ПРИНЦИП:
Каждое слово — про ЭТОГО конкретного человека.
Запрещены общие фразы не связанные с фото.

ВАЖНЕЙШЕЕ ПРАВИЛО ПО ПРИРОДНЫМ ЧЕРТАМ:
Всё что дано природой — форма костей, форма носа, асимметрия,
пропорции лица, форма глаз — это СИЛЬНЫЕ СТОРОНЫ и УНИКАЛЬНОСТЬ.
Показывай как эти черты подчеркнуть и использовать в свою пользу.
НИКОГДА не критикуй природные черты как недостаток.

Критикуй ТОЛЬКО то что человек реально может изменить:
состояние кожи, причёску, брови, стиль одежды, цвет одежды, уход за собой.

ТОН: честный умный друг-эксперт. Говори правду с уважением.
Не льсти, не унижай. Негативное подавай как зону роста с конкретным решением.

Ответь строго в этом формате (на русском языке):

ОЦЕНКА: [число от 1 до 10, можно дробное например 7.5]
[1-2 предложения — что конкретно держит оценку вверху и что можно улучшить]

АРХЕТИП: [одно из: Охотник / Лис / Красавчик / Атлет / Медведь]
[2-3 предложения — объясни через конкретные черты лица почему именно этот архетип]

ПОХОЖ НА: [имя 1-2 знаменитостей]
[какие именно черты совпадают]

РАЗБОР ЛИЦА:
- ГЛАЗА: [canthal tilt, посадка, что создаёт за взгляд — как это работает в пользу человека]
- КОСТНАЯ СТРУКТУРА: [скулы, челюсть, подбородок — как эти природные черты являются преимуществом]
- КОЖА: [тон, текстура, что видно на фото — только изменяемые аспекты]
- БРОВИ: [форма, плотность, как влияют на взгляд]
- СИММЕТРИЯ: [любая асимметрия — подавай как уникальность и характер, не как недостаток]

ЦВЕТОТИП: [название сезона например Тёплая Осень / Яркая Зима / Мягкое Лето и т.д.]
[2-3 предложения — какие цвета в одежде усиливают внешность, какие гасят]

ТИПАЖ КИББИ: [название типажа например Natural / Dramatic / Classic и т.д.]
[какие силуэты и стиль одежды работают на этот тип]

ПРИЧЁСКА: [конкретно что подойдёт под форму лица и почему — как усилить природные черты]

СИЛЬНЫЕ СТОРОНЫ:
- [природная черта + как её подчеркнуть и использовать]
- [пункт 2]
- [пункт 3]

ЗОНЫ РОСТА:
- [только изменяемое: кожа/причёска/брови/стиль + конкретное решение]
- [пункт 2]
- [пункт 3]

ПЛАН НА 30 ДНЕЙ:
- НЕДЕЛЯ 1: [конкретные действия под главную зону роста]
- НЕДЕЛЯ 2: [следующий уровень]
- НЕДЕЛЯ 3: [усложнение]
- НЕДЕЛЯ 4: [закрепление]

ПОТЕНЦИАЛ: [до какой оценки реально вырасти, за сколько, через конкретные изменяемые черты]"""

        response = client.chat.completions.create(
            model="google/gemini-2.0-flash-001",
            messages=[{
                "role": "user",
                "content": [
                    {
                        "type": "image_url",
                        "image_url": {"url": f"data:image/jpeg;base64,{image_data}"}
                    },
                    {
                        "type": "text",
                        "text": prompt
                    }
                ]
            }],
            max_tokens=1500,
            temperature=0.3
        )

        result_text = response.choices[0].message.content
        return jsonify({"success": True, "result": result_text})

    except Exception as e:
        return jsonify({"success": False, "error": str(e)})

if __name__ == '__main__':
    app.run()
