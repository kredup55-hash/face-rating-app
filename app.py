from flask import Flask, render_template, request, jsonify
from openai import OpenAI
import base64
import os

app = Flask(__name__)

client = OpenAI(
    api_key=os.environ.get("OPENROUTER_API_KEY"),
    base_url="https://openrouter.ai/api/v1"
)

@app.route('/')
def index():
    return render_template('index.html')

@app.route('/analyze', methods=['POST'])
def analyze():
    try:
        file = request.files['photo']
        image_data = base64.b64encode(file.read()).decode('utf-8')

        prompt = """Ты — лучший в мире эксперт по мужской эстетике и стилю.
Твоя методология объединяет: QOVES Studio (2000+ научных исследований по эстетике лица),
PSL-метрики looksmaxxing-сообщества, систему типажей David Kibbe,
Seasonal Color Analysis (12 сезонов), подход David Zyla,
практики ведущих российских имидж-консультантов.

ГЛАВНЫЙ ПРИНЦИП (из методологии QOVES):
Выявляй конкретные зоны как дерматолог или эстетик на приёме.
Каждое слово — про ЭТОГО конкретного человека.
ЗАПРЕЩЕНО: общие фразы, советы не связанные с фото, одинаковые рекомендации разным людям.

Ответь строго в этом формате (на русском языке):

ОЦЕНКА: [число от 1 до 10, можно дробное например 7.5]
[1-2 предложения — что конкретно тянет оценку вниз и что держит вверху]

АРХЕТИП: [одно из: Охотник / Лис / Красавчик / Атлет / Медведь]
[2-3 предложения — объясни через его конкретные черты лица почему именно этот архетип]

ПОХОЖ НА: [имя 1-2 знаменитостей]
[какие именно черты совпадают]

РАЗБОР ЛИЦА:
- ГЛАЗА: [canthal tilt положительный/нейтральный/отрицательный, посадка, что создаёт за взгляд]
- КОСТНАЯ СТРУКТУРА: [скулы, челюсть, подбородок, какая треть доминирует]
- КОЖА: [тон, текстура, главные проблемы видимые на фото]
- БРОВИ: [форма, плотность, как влияют на взгляд]
- СИММЕТРИЯ: [есть ли асимметрии, как влияют]

ЦВЕТОТИП: [название сезона например Тёплая Осень / Яркая Зима / Мягкое Лето и т.д.]
[2-3 предложения — какие цвета в одежде усиливают его внешность, какие гасят]

ТИПАЖ КИББИ: [название типажа например Natural / Dramatic / Classic и т.д.]
[какие силуэты и стиль одежды работают на его тип тела и линии]

ПРИЧЁСКА: [конкретно что подойдёт под форму его лица и почему]

СИЛЬНЫЕ СТОРОНЫ:
- [конкретная черта + почему она работает в его пользу]
- [пункт 2]
- [пункт 3]

ЧТО УЛУЧШИТЬ:
- [конкретная черта + как именно она влияет на восприятие + что делать]
- [пункт 2]
- [пункт 3]

ПЛАН НА 30 ДНЕЙ:
- НЕДЕЛЯ 1: [конкретные действия под его главную проблему с фото]
- НЕДЕЛЯ 2: [следующий уровень]
- НЕДЕЛЯ 3: [усложнение]
- НЕДЕЛЯ 4: [закрепление]

ПОТЕНЦИАЛ: [до какой оценки реально вырасти, за сколько, обоснуй через его конкретные черты]"""

        response = client.chat.completions.create(
            model="google/gemini-2.0-flash-001",
            messages=[{
                "role": "user",
                "content": [
                    {
                        "type": "image_url",
                        "image_url": {"url": f"data:image/jpeg;base64,{image_data}"}
                    },
                    {
                        "type": "text",
                        "text": prompt
                    }
                ]
            }],
            max_tokens=1500
        )

        result_text = response.choices[0].message.content
        return jsonify({"success": True, "result": result_text})

    except Exception as e:
        return jsonify({"success": False, "error": str(e)})

if __name__ == '__main__':
    app.run()
