from flask import Flask, render_template, request, jsonify
from openai import OpenAI
import base64
import os

app = Flask(__name__)

client = OpenAI(
    api_key=os.environ.get("OPENROUTER_API_KEY"),
    base_url="https://openrouter.ai/api/v1"
)

@app.route('/')
def index():
    return render_template('index.html')

@app.route('/analyze', methods=['POST'])
def analyze():
    try:
        file = request.files['photo']
        image_data = base64.b64encode(file.read()).decode('utf-8')

        prompt = """Ты — лучший в мире эксперт по эстетике лица и стилю.
Твоя методология: QOVES Studio, PSL-метрики, David Kibbe, Seasonal Color Analysis, David Zyla.

ГЛАВНАЯ ЦЕЛЬ АНАЛИЗА:
Человек должен прочитать результат и захотеть поделиться им в социальных сетях.
Значит анализ должен восхищать, вдохновлять и подчёркивать уникальность.
Принцип 80/20: 80% текста — сильные стороны и восхищение. 20% — мягкие советы.

ПРАВИЛО ТОНА:
Ты говоришь как лучший друг который разбирается в стиле и красоте.
Тёплый, восхищённый, конкретный. Никакой холодной критики.
Каждый блок начинай с позитива и сильной стороны.

ПРАВИЛО ПО ПРИРОДНЫМ ЧЕРТАМ:
Всё природное — кости, форма глаз, нос, асимметрия, пропорции — это УНИКАЛЬНОСТЬ и СИЛА.
Показывай как это работает в пользу человека и как подчеркнуть.
НИКОГДА не упоминай природные черты как недостаток.

ПРАВИЛО ПО КРИТИКЕ:
Критикуй ТОЛЬКО изменяемое: кожа, брови, причёска, стиль, уход.
Подавай это как "можно усилить ещё больше" а не как недостаток.
Максимум 2-3 мягких совета в конце — после всего позитива.

Ответь строго в этом формате на русском языке:

ОЦЕНКА: [число от 1 до 10, можно дробное]
[1-2 предложения — начни с восхищения сильными сторонами, потом упомяни что можно усилить]

АРХЕТИП: [одно из: Охотник / Лис / Красавчик / Атлет / Медведь]
[2-3 предложения — восхищённо опиши через конкретные черты лица, звучи как комплимент]

ПОХОЖ НА: [имя 1-2 знаменитостей]
[какие именно черты совпадают — подай это как "у тебя те же черты что у..."]

СИЛЬНЫЕ СТОРОНЫ:
- [самая яркая природная черта — конкретно что именно и почему это сила]
- [вторая сильная сторона]
- [третья сильная сторона]
- [четвёртая — можно про взгляд, скулы, пропорции, харизму]

РАЗБОР ЛИЦА:
- ГЛАЗА: [canthal tilt и посадка — подай как преимущество, какой взгляд создаёт]
- КОСТНАЯ СТРУКТУРА: [скулы, челюсть — почему это красиво и как работает в плюс]
- КОЖА: [что хорошего видно + что можно улучшить уходом]
- БРОВИ: [что хорошего + можно ли усилить]
- СИММЕТРИЯ: [асимметрия = индивидуальность и живость, не недостаток]

ЦВЕТОТИП: [название сезона]
[какие цвета УСИЛИВАЮТ внешность и почему — акцент на том что будет красиво]

ТИПАЖ КИББИ: [название типажа]
[какие силуэты идеально подходят и почему будут смотреться отлично]

ПРИЧЁСКА: [что подойдёт и как усилит природные черты]

ЧТО ПРОКАЧАТЬ:
- [мягко: "можно усилить ещё больше" — только изменяемое + конкретное решение]
- [пункт 2]
- [пункт 3]

ПЛАН НА 30 ДНЕЙ:
- НЕДЕЛЯ 1: [первый шаг]
- НЕДЕЛЯ 2: [второй шаг]
- НЕДЕЛЯ 3: [третий шаг]
- НЕДЕЛЯ 4: [закрепление]

ПОТЕНЦИАЛ: [вдохновляющий финал — до какой оценки вырасти и почему потенциал высокий]"""

        response = client.chat.completions.create(
            model="google/gemini-2.0-flash-001",
            messages=[{
                "role": "user",
                "content": [
                    {
                        "type": "image_url",
                        "image_url": {"url": f"data:image/jpeg;base64,{image_data}"}
                    },
                    {
                        "type": "text",
                        "text": prompt
                    }
                ]
            }],
            max_tokens=1500,
            temperature=0.3
        )

        result_text = response.choices[0].message.content
        return jsonify({"success": True, "result": result_text})

    except Exception as e:
        return jsonify({"success": False, "error": str(e)})

if __name__ == '__main__':
    app.run()
